"""Competition metadata: fetched from Kaggle, rendered as docs/competition.md for humans and agents."""

from __future__ import annotations

import json
import re
from datetime import datetime, timezone
from pathlib import Path

from kx.kaggle import client as kaggle, scoring
from kx.ledger.store import now

META_FILE = "docs/competition.md"

# Rendered first, in this order; other pages follow in Kaggle's order.
PAGE_ORDER = ["abstract", "description", "background", "evaluation", "code requirements",
              "data-description", "timeline", "prizes"]
# Long boilerplate: linked, not inlined.
SKIP_PAGES = {"foundational-rules"}

WORDS = {"one": 1, "two": 2, "three": 3, "four": 4, "five": 5, "six": 6, "seven": 7, "eight": 8, "nine": 9, "ten": 10}


def fetch(slug: str) -> dict:
    return {
        "slug": slug,
        "fetched": now(),
        "competition": kaggle.competition(slug),
        "pages": kaggle.pages(slug),
        "files": kaggle.files(slug),
    }


def _page(meta: dict, name: str) -> str:
    return next((p.get("content") or "" for p in meta["pages"] if p["name"].lower() == name), "")


def infer(meta: dict) -> dict:
    """Best-effort comp.yaml defaults from the competition pages. Always printed for review."""
    names = {p["name"].lower() for p in meta["pages"]}
    evaluation = _page(meta, "evaluation")
    out, why = {}, {}
    if re.search(r"\bepisodes?\b", evaluation, re.I) and re.search(r"rating", evaluation, re.I):
        out["kind"], why["kind"] = "simulation", "Evaluation page talks about episodes and skill ratings"
    elif "code requirements" in names:
        out["kind"], why["kind"] = "code", "competition has a 'Code Requirements' page"
    else:
        out["kind"], why["kind"] = "file", "no code requirements / episodes found"
    text = " ".join(p.get("content") or "" for p in meta["pages"])
    m = (re.search(r"maximum of (?:\w+ )?\((\d+)\) submissions per day", text, re.I)
         or re.search(r"up to (\d+) (?:submissions|agents)\b[^.]{0,40}(?:per day|each day)", text, re.I)
         or re.search(r"submit up to (\d+) agents", text, re.I))
    if m:
        out["daily_limit"], why["daily_limit"] = int(m.group(1)), f"rules: “{m.group(0)}”"
    out["mode"], why["mode"] = scoring.infer(evaluation, out["kind"])
    first = evaluation.strip().split("\n")[0][:200] if evaluation else ""
    if first:
        why["metric"] = f"Evaluation page: “{first}”"
    return {"values": out, "why": why}


def _days_left(deadline: str | None) -> str:
    if not deadline:
        return ""
    try:
        d = datetime.fromisoformat(deadline).replace(tzinfo=timezone.utc) - datetime.now(timezone.utc)
    except ValueError:
        return ""
    return f" ({d.days} days left)" if d.days >= 0 else " (ended)"


def _size(n: int | float | None) -> str:
    if n is None:
        return "-"
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:.0f} {unit}" if unit == "B" else f"{n:.1f} {unit}"
        n /= 1024


def _files_section(files: list[dict], limit: int = 40) -> list[str]:
    total = sum(f.get("size") or 0 for f in files)
    out = [f"{len(files)} file(s), {_size(total)} total. Local copy: `data/` (see `kx data`).", ""]
    top = [f for f in files if "/" not in f["name"]]
    nested: dict[str, list] = {}
    for f in files:
        if "/" in f["name"]:
            nested.setdefault(f["name"].split("/")[0], []).append(f)
    out += ["| file | size | updated |", "|---|---:|---|"]
    for f in top[:limit]:
        out.append(f"| `{f['name']}` | {_size(f.get('size'))} | {(f.get('creationDate') or '')[:10]} |")
    for d, fs in nested.items():
        out.append(f"| `{d}/` ({len(fs)} files) | {_size(sum(x.get('size') or 0 for x in fs))} | "
                   f"{max((x.get('creationDate') or '') for x in fs)[:10]} |")
    if len(top) > limit:
        out.append(f"| … {len(top) - limit} more | | |")
    return out


def render(meta: dict, comp) -> str:
    c = meta["competition"]
    url = c.get("ref") or f"https://www.kaggle.com/competitions/{meta['slug']}"
    title = meta["slug"].replace("-", " ").title()
    lines = [
        f"<!-- generated by `kx meta` on {meta['fetched']}; do not edit, regenerate instead. -->",
        f"# {title}",
        "",
        "| | |",
        "|---|---|",
        f"| URL | {url} |",
        f"| Category | {c.get('category', '-')} · reward {c.get('reward', '-')} |",
        f"| Deadline | {c.get('deadline', '-')} UTC{_days_left(c.get('deadline'))} |",
        f"| Teams | {c.get('teamCount', '-')} |",
        f"| Entered | {'yes' if c.get('userHasEntered') else '**no — accept the rules on kaggle.com before downloading/submitting**'} |",
        f"| kx | kind `{comp.kind}` · metric `{comp.metric}` ({comp.direction}) · "
        f"daily limit {comp.submission.get('daily_limit', '-')} |",
        "",
    ]
    pages = {p["name"]: p.get("content") or "" for p in meta["pages"]}
    ordered = sorted(pages, key=lambda n: PAGE_ORDER.index(n.lower()) if n.lower() in PAGE_ORDER else len(PAGE_ORDER))
    toc = [n for n in ordered if n not in SKIP_PAGES and pages[n].strip()]
    lines += ["**Contents:** " + " · ".join(toc) + " · Files", ""]
    for name in toc:
        body = pages[name].strip()
        # demote the page's own headings below our section heading
        body = re.sub(r"^(#{1,5}) ", lambda m: "#" * min(len(m.group(1)) + 2, 6) + " ", body, flags=re.M)
        lines += [f"## {name.replace('-', ' ').title() if name.islower() else name}", "", body, ""]
    skipped = [n for n in pages if n in SKIP_PAGES]
    if skipped:
        lines += [f"_Not inlined: {', '.join(skipped)} — see {url}/rules._", ""]
    lines += ["## Files", ""] + _files_section(meta["files"]) + [""]
    return "\n".join(lines)


def write(comp, meta: dict) -> Path:
    comp.store.mkdir(parents=True, exist_ok=True)
    (comp.store / "meta.json").write_text(json.dumps(meta, indent=2))
    path = comp.root / META_FILE
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(meta, comp))
    return path


def load_cached(comp) -> dict | None:
    p = comp.store / "meta.json"
    return json.loads(p.read_text()) if p.exists() else None


KAGGLE = "https://www.kaggle.com"


def links(comp) -> dict[str, str]:
    """The competition's Kaggle pages (and its submission kernel, for code competitions)."""
    base = f"{KAGGLE}/competitions/{comp.slug}"
    out = {"competition": base, **{p: f"{base}/{p}" for p in ("data", "leaderboard", "submissions", "discussion", "code",
                                                                 "rules")}}
    if comp.submission.get("kernel"):
        out["kernel"] = kernel_url(comp.submission["kernel"])
    return out


def kernel_url(ref: str) -> str:
    """A notebook's page from 'owner/slug' (or a submission target 'kernel:owner/slug@version')."""
    ref = ref.removeprefix("kernel:").split("@", 1)[0]
    return f"{KAGGLE}/code/{ref}"


def dataset_url(ref: str) -> str:
    return f"{KAGGLE}/datasets/{ref}"


def push_url(kind: str, target: str) -> str | None:
    return kernel_url(target) if kind == "kernel" else dataset_url(target) if kind == "dataset" else None
